import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { describe, it } from "node:test";
import { STORIES } from "../src/lib/cfb/stories.ts";
import { buildSitemap, SITEMAP_PATH, sitemapPaths } from "./generate-sitemap.mjs";

describe("build-time sitemap", () => {
  const xml = buildSitemap();
  const locs = [...xml.matchAll(/<loc>([^<]+)<\/loc>/g)].map((m) => m[1]);

  it("has no /edge entries (Edge is paused)", () => {
    assert.equal(locs.filter((l) => /\/edge(\/|$|\?)/.test(l)).length, 0);
  });
  it("lists all 136 FBS team pages and every story", () => {
    assert.equal(locs.filter((l) => l.includes("/teams/")).length, 136);
    for (const s of STORIES) assert.ok(locs.includes(`https://hashmarkcfb.com/stories/${s.slug}`), s.slug);
  });
  it("has unique URLs and escapes nothing unsafe", () => {
    assert.equal(new Set(locs).size, locs.length);
    assert.equal(locs.length, sitemapPaths().length);
    assert.doesNotMatch(xml, /&(?!amp;|lt;|gt;)/);
  });
  it("is the build-generated file", () => {
    assert.equal(readFileSync(SITEMAP_PATH, "utf8"), xml);
  });
  it("is generated by npm run build", () => {
    const pkg = JSON.parse(readFileSync(new URL("../package.json", import.meta.url), "utf8"));
    assert.match(pkg.scripts.build, /generate-sitemap\.mjs/);
  });
});
